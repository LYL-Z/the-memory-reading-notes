def read(p):
    with io.open(p, "r", encoding="utf-8", newline="") as f:
        return f.read()


def write(p, t):
    t = t.replace("\r\n", "\n").replace("\n", "\r\n")
    with io.open(p, "w", encoding="utf-8", newline="") as f:
        f.write(t)


def run(path, reps, label):
    t = read(path)
    miss = []
    for old, new in reps:
        n = t.count(old)
        if n != 1:
            miss.append((old[:52], n))
            continue
        t = t.replace(old, new, 1)
    write(path, t)
    print("%s: %d/%d applied" % (label, len(reps) - len(miss), len(reps)))
    for m in miss:
        print("  MISS count=%d : %s" % (m[1], m[0]))
    return len(miss)


