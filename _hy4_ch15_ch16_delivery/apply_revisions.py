def read(p):
    with io.open(p, "r", encoding="utf-8", newline="") as f:
        return f.read()


def write(p, t):
    # 统一为 CRLF，与仓库既有正文一致
    t = t.replace("\r\n", "\n").replace("\n", "\r\n")
    with io.open(p, "w", encoding="utf-8", newline="") as f:
        f.write(t)


def apply_reps(path, reps, label):
    t = read(path)
    ok, miss = 0, []
    for old, new in reps:
        n = t.count(old)
        if n != 1:
            miss.append((old[:40], n))
            continue
        t = t.replace(old, new, 1)
        ok += 1
    write(path, t)
    print("%s: applied %d/%d" % (label, ok, len(reps)))
    for m in miss:
        print("  MISS count=%d : %s" % (m[1], m[0]))
    return len(miss)


