def main():
    ok, miss = 0, []
    for ch, reps in R.items():
        path = os.path.join(BASE, ch + ".md")
        with io.open(path, "r", encoding="utf-8", newline="") as f:
            text = f.read()
        before = text
        for i, (old, new) in enumerate(reps, 1):
            n = text.count(old)
            if n != 1:
                miss.append((ch, i, n, old[:40]))
                continue
            text = text.replace(old, new, 1)
            ok += 1
        if text != before:
            with io.open(path, "w", encoding="utf-8", newline="") as f:
                f.write(text)
        print("%s: %d/%d applied, %d -> %d chars" % (
            ch, sum(1 for m in miss if m[0] != ch) * 0 + len(reps) - len([m for m in miss if m[0] == ch]),
            len(reps), len(before), len(text)))
    print("\nAPPLIED =", ok)
    if miss:
        print("MISSED (%d):" % len(miss))
        for ch, i, n, snip in miss:
            print("  %s #%d count=%d : %s" % (ch, i, n, snip))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
